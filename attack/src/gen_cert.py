#!/usr/bin/env python3
"""Generate an independently checkable Lean certificate for binary Goldbach up to N.

For every even n in [4, N], find a prime pair p+q=n with a sieve, then emit a Lean file
where each case is proved by explicit witnesses + norm_num primality (no decide/native_decide).

Usage: python3 src/gen_cert.py --n 200 --out lean/Goldbach/Finite200.lean
"""
import argparse, pathlib

def sieve(n):
    prime = bytearray(b"\x01") * (n + 1)
    if n >= 0: prime[0] = 0
    if n >= 1: prime[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if prime[i]:
            prime[i*i::i] = b"\x00" * len(prime[i*i::i])
    return prime

def generate(N):
    prime = sieve(N)
    pairs = {}
    for n in range(4, N + 1, 2):
        found = None
        for p in range(2, n // 2 + 1):
            if prime[p] and prime[n - p]:
                found = (p, n - p); break
        if found is None:
            raise SystemExit(f"NO GOLDBACH PAIR for even n={n} up to N={N} — check sieve")
        pairs[n] = found

    lines = [
        "import Mathlib", "import Goldbach.Basic", "",
        "-- Machine-generated by src/gen_cert.py. Explicit witnesses; no decide/native_decide.",
        f"-- Binary Goldbach verified by kernel for all even 4 <= n <= {N}.",
        "", "namespace GoldbachAttack", "",
        f"set_option maxHeartbeats {max(200000, N * 400)} in",
        f"theorem binaryGoldbachUpTo_{N} : BinaryGoldbachUpTo {N} := by",
        "  intro n hn2 hnN hneven",
        "  obtain ⟨k, rfl⟩ := hneven",
        f"  have hk : k ≤ {N // 2} := by omega",
        "  interval_cases k <;> try omega",
    ]
    for k in range(2, N // 2 + 1):
        p, q = pairs[2 * k]
        lines.append(f"  · exact ⟨{p}, {q}, by norm_num [Nat.prime_def_lt], by norm_num [Nat.prime_def_lt], by norm_num⟩")
    lines += ["", "end GoldbachAttack", ""]
    return "\n".join(lines), pairs

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    src, pairs = generate(a.n)
    pathlib.Path(a.out).write_text(src, encoding="utf-8")
    print(f"wrote {a.out}: {len(src)} bytes, {len(pairs)} even n certified up to {a.n}")

if __name__ == "__main__":
    main()
